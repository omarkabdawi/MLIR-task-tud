#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

/* Descriptor for a dynamically sized 2D MLIR memref. */
typedef struct {
    double *allocated;
    double *aligned;
    int64_t offset;
    int64_t sizes[2];
    int64_t strides[2];
} MemRef2D;

/* C-interface wrapper for func.func @matmul_named. */
void _mlir_ciface_matmul_named(
    MemRef2D *A,
    MemRef2D *B,
    MemRef2D *C
);

int main(void) {
    
    double A_data[6] = {1, 2, 3, 4, 5, 6};
    double B_data[6] = {7, 8, 9, 10, 11, 12};
    double C_data[4] = {0, 0, 0, 0};

    MemRef2D A = {
        A_data, A_data, 0, {2, 3}, {3, 1}
    };
    MemRef2D B = {
        B_data, B_data, 0, {3, 2}, {2, 1}
    };
    MemRef2D C = {
        C_data, C_data, 0, {2, 2}, {2, 1}
    };

    /* Call the matrix multiplication generated by MLIR. */
    _mlir_ciface_matmul_named(&A, &B, &C);

 
    const double expected[4] = {58, 64, 139, 154};

    printf("Result C:\n");
    for (int i = 0; i < 2; ++i) {
        for (int j = 0; j < 2; ++j) {
            printf("%8.1f ", C_data[i * 2 + j]);
        }
        printf("\n");
    }

    for (int i = 0; i < 4; ++i) {
        if (C_data[i] != expected[i]) {
            fprintf(stderr,
                    "Test failed at element %d: got %f, expected %f\n",
                    i, C_data[i], expected[i]);
            return EXIT_FAILURE;
        }
    }

    printf("Test passed!\n");
    return EXIT_SUCCESS;
}